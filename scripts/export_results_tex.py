#!/usr/bin/env python3
"""Export snapshot-visible results into TeX macros and tables."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List

NOTES = {
    "stencil_flow": Path("notes/stencil_flow_last_run.json"),
    "stencil_leibniz": Path("notes/stencil_flow_leibniz_last_run.json"),
    "holonomy": Path("notes/holonomy_rm_last_run.json"),
    "prime_closure": Path("notes/prime_closure_rm_last_run.json"),
    "passivity": Path("notes/passivity_toy_last_run.json"),
}
OUT_DIR = Path("tex/math_instantiation/generated")


def read_json(path: Path) -> Dict[str, Any]:
    if not path.exists():
        raise FileNotFoundError(f"Missing required input: {path}")
    return json.loads(path.read_text())


def fmt_num(x: Any, *, math: bool = False) -> str:
    try:
        val = float(x)
    except Exception as exc:  # noqa: BLE001
        raise ValueError(f"Cannot format non-numeric value: {x}") from exc
    if val == 0:
        return "0"
    absval = abs(val)
    if 1e-3 <= absval < 1e4:
        out = f"{val:.6g}"
        return f"\\ensuremath{{{out}}}" if math else out
    exp = int(f"{val:.0e}".split("e")[1])
    mant = val / (10 ** exp)
    out = f"{mant:.6g}\\times 10^{{{exp}}}"
    return f"\\ensuremath{{{out}}}" if math else out


def header() -> str:
    return "% Auto-generated by scripts/export_results_tex.py from notes/*_last_run.json\n"


def write_file(path: Path, content: str) -> None:
    path.write_text(header() + content + "\n", encoding="utf-8")


def make_table(caption: str, label: str, columns: str, rows: List[List[str]]) -> str:
    lines: List[str] = []
    lines.append("\\begin{table}[h]")
    lines.append("\\centering")
    lines.append(f"\\caption{{{caption}}}")
    lines.append(f"\\label{{{label}}}")
    lines.append(f"\\begin{{tabular}}{{{columns}}}")
    lines.append("\\hline")
    for row in rows:
        lines.append(" " + " & ".join(row) + r" \\")
        lines.append("\\hline")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    return "\n".join(lines)


def format_k_counts(raw: Any) -> str:
    if not isinstance(raw, dict):
        return str(raw)
    def get_val(k: int) -> Any:
        return raw.get(str(k), raw.get(k, 0))
    parts = [f"k={k}: {get_val(k)}" for k in (0, 1, 2)]
    return "; ".join(parts)


def format_set(values: Any) -> str:
    if not isinstance(values, list):
        return str(values)
    parts: List[str] = []
    for v in values:
        if isinstance(v, float) and v.is_integer():
            parts.append(str(int(v)))
        else:
            parts.append(str(v))
    return r"\{" + ",".join(parts) + r"\}"


def main() -> int:
    data = {key: read_json(path) for key, path in NOTES.items()}

    OUT_DIR.mkdir(parents=True, exist_ok=True)

    hol_p = data["holonomy"].get("fit_p")
    hol_r2 = data["holonomy"].get("fit_r2")
    hol_null_max = data["holonomy"].get("null_rm_max")
    stencil_total = data["stencil_flow"].get("generated_total")
    stencil_survivors = data["stencil_flow"].get("survivors_total")
    stencil_leib_survivors = data["stencil_leibniz"].get("survivors_total")
    stencil_params = data["stencil_flow"].get("params", {})
    leib_params = data["stencil_leibniz"].get("params", {})
    prime_params = data["prime_closure"].get("params", {})
    passivity_params = data["passivity"].get("params", {})

    conv_table = data["prime_closure"].get("conv_table", [])
    strip_table = data["prime_closure"].get("strip_table", [])

    def rm_at_800(table: List[List[Any]]) -> Any:
        for row in table:
            if int(row[0]) == 800:
                return row[1]
        return None

    prime_conv_800 = rm_at_800(conv_table)
    prime_strip_800 = rm_at_800(strip_table)

    passivity_table = data["passivity"].get("table", [])
    passivity_l1 = None
    passivity_l0 = None
    for row in passivity_table:
        if float(row[0]) == 1.0:
            passivity_l1 = row[1]
        if float(row[0]) == 0.0:
            passivity_l0 = row[1]

    macros = []
    macros.append(
        f"\\newcommand{{\\HolonomyExponent}}{{\\ensuremath{{{fmt_num(hol_p)}}}}}"
    )
    macros.append(
        f"\\newcommand{{\\StencilGeneratedTotal}}{{\\ensuremath{{{stencil_total}}}}}"
    )
    macros.append(
        f"\\newcommand{{\\StencilSurvivorsTotal}}{{\\ensuremath{{{stencil_survivors}}}}}"
    )
    macros.append(
        f"\\newcommand{{\\StencilLeibnizSurvivorsTotal}}{{\\ensuremath{{{stencil_leib_survivors}}}}}"
    )
    macros.append(
        f"\\newcommand{{\\StencilNZero}}{{\\ensuremath{{{stencil_params.get('N0')}}}}}"
    )
    macros.append(
        f"\\newcommand{{\\StencilMLeibniz}}{{\\ensuremath{{{leib_params.get('m')}}}}}"
    )
    macros.append(
        f"\\newcommand{{\\StencilGateDTwo}}{{\\ensuremath{{{fmt_num(leib_params.get('gate_D2'))}}}}}"
    )
    macros.append(
        f"\\newcommand{{\\StencilGateRatio}}{{\\ensuremath{{{fmt_num(leib_params.get('gate_ratio'))}}}}}"
    )
    macros.append(
        f"\\newcommand{{\\PrimeRMConvAtEightHundred}}{{\\ensuremath{{{fmt_num(prime_conv_800)}}}}}"
    )
    macros.append(
        f"\\newcommand{{\\PrimeRMStripAtEightHundred}}{{\\ensuremath{{{fmt_num(prime_strip_800)}}}}}"
    )
    macros.append(
        f"\\newcommand{{\\HolonomyFitRtwo}}{{\\ensuremath{{{fmt_num(hol_r2)}}}}}"
    )
    macros.append(
        f"\\newcommand{{\\HolonomyNullRMMax}}{{\\ensuremath{{{fmt_num(hol_null_max)}}}}}"
    )
    macros.append(
        f"\\newcommand{{\\PrimeDPS}}{{\\ensuremath{{{prime_params.get('dps')}}}}}"
    )
    macros.append(
        f"\\newcommand{{\\PassivityN}}{{\\ensuremath{{{passivity_params.get('n')}}}}}"
    )
    macros.append(
        f"\\newcommand{{\\PrimeNList}}{{\\ensuremath{{{format_set(prime_params.get('N_list'))}}}}}"
    )
    macros.append(
        f"\\newcommand{{\\PrimeSigmaConvList}}{{\\ensuremath{{{format_set(prime_params.get('sigma_conv_list'))}}}}}"
    )
    macros.append(
        f"\\newcommand{{\\PrimeSigmaStripList}}{{\\ensuremath{{{format_set(prime_params.get('sigma_strip_list'))}}}}}"
    )
    macros.append(
        f"\\newcommand{{\\PrimeTList}}{{\\ensuremath{{{format_set(prime_params.get('t_list'))}}}}}"
    )
    macros.append(
        f"\\newcommand{{\\PassivityMeanDevLamOne}}{{\\ensuremath{{{fmt_num(passivity_l1)}}}}}"
    )
    macros.append(
        f"\\newcommand{{\\PassivityMeanDevLamZero}}{{\\ensuremath{{{fmt_num(passivity_l0)}}}}}"
    )
    write_file(OUT_DIR / "macros.tex", "\n".join(macros))

    stab = data["stencil_flow"]
    stab_row = [
        str(stab.get("generated_total")),
        str(stab.get("survivors_total")),
        format_k_counts(stab.get("survivors_by_best_fit_k")),
    ]
    stab_rows = [["generated", "survivors", "best-fit counts"], stab_row]
    stab_table = make_table(
        "Stencil flow stability-only summary",
        "tab:stencil-stability",
        "l|l|l",
        stab_rows,
    )
    write_file(OUT_DIR / "stencil_stability_table.tex", stab_table)

    leib = data["stencil_leibniz"]
    leib_row = [
        str(leib.get("survivors_total")),
        format_k_counts(leib.get("survivors_by_best_fit_k")),
    ]
    leib_rows = [["survivors", "best-fit counts"], leib_row]
    leib_table = make_table(
        "Leibniz-gated stencil selection",
        "tab:stencil-leibniz",
        "l|l",
        leib_rows,
    )
    write_file(OUT_DIR / "stencil_leibniz_table.tex", leib_table)

    top_rows = [["rank", "D2", "F1", "\\ensuremath{E_{12,1}}"]]
    for row in leib.get("table", [])[:10]:
        top_rows.append(
            [
                str(row[0]),
                fmt_num(row[1], math=True),
                fmt_num(row[2], math=True),
                fmt_num(row[3], math=True),
            ]
        )
    top_table = make_table(
        "Leibniz-gated top survivors (diagnostics)",
        "tab:stencil-leibniz-top",
        "l|l|l|l",
        top_rows,
    )
    write_file(OUT_DIR / "stencil_leibniz_top_table.tex", top_table)

    hol_table_rows = [["$h$", "RM"]]
    for row in data["holonomy"].get("table", []):
        hol_table_rows.append([fmt_num(row[0], math=True), fmt_num(row[1], math=True)])
    hol_table = make_table(
        "Holonomy RM vs h",
        "tab:holonomy",
        "l|l",
        hol_table_rows,
    )
    write_file(OUT_DIR / "holonomy_table.tex", hol_table)

    conv_rows = [["N", "RM2", "errS2", "errP2"]]
    for row in conv_table:
        conv_rows.append(
            [
                str(row[0]),
                fmt_num(row[1], math=True),
                fmt_num(row[2], math=True),
                fmt_num(row[3], math=True),
            ]
        )
    conv_table_tex = make_table(
        "Prime RM in convergence region",
        "tab:prime-rm-conv",
        "l|l|l|l",
        conv_rows,
    )
    write_file(OUT_DIR / "prime_rm_conv_table.tex", conv_table_tex)

    strip_rows = [["N", "RM2", "errS2", "errP2"]]
    for row in strip_table:
        strip_rows.append(
            [
                str(row[0]),
                fmt_num(row[1], math=True),
                fmt_num(row[2], math=True),
                fmt_num(row[3], math=True),
            ]
        )
    strip_table_tex = make_table(
        "Prime RM in the critical strip",
        "tab:prime-rm-strip",
        "l|l|l|l",
        strip_rows,
    )
    write_file(OUT_DIR / "prime_rm_strip_table.tex", strip_table_tex)

    pass_rows = [["$\\lambda$", "mean\\_dev", "max\\_dev"]]
    for row in passivity_table:
        pass_rows.append(
            [
                fmt_num(row[0], math=True),
                fmt_num(row[1], math=True),
                fmt_num(row[2], math=True),
            ]
        )
    pass_table_tex = make_table(
        "Passivity toy zero-confinement metrics",
        "tab:passivity",
        "l|l|l",
        pass_rows,
    )
    pass_table_tex = pass_table_tex.replace("\\begin{table}[h]", "\\begin{table}[H]", 1)
    write_file(OUT_DIR / "passivity_table.tex", pass_table_tex)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
