#!/usr/bin/env python3
"""Export the reviewed experiment artifacts into TeX macros and tables.

Inputs are the commit-visible artifacts under notes/math_review/, which are
regenerated by `bash scripts/check_all.sh --math-only`. The historical
notes/*_last_run.json pointers are not read.
"""

from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Any, Dict, List, Sequence

REVIEW = Path("notes/math_review")
INPUTS = {
    "stencil_baseline": REVIEW / "stencil_baseline_run.json",
    "stencil_legacy": REVIEW / "stencil_leibniz_run.json",
    "stencil_matched": REVIEW / "stencil_matched_controls.json",
    "stencil_hunt": REVIEW / "stencil_false_positives.json",
    "holonomy": REVIEW / "holonomy_run.json",
    "integration": REVIEW / "integration_run.json",
    "prime": REVIEW / "prime_run.json",
    "passivity": REVIEW / "passivity_run.json",
    "verification": REVIEW / "verification.json",
}
OUT_DIR = Path("tex/math_instantiation/generated")
HEADER = "% Auto-generated by scripts/export_results_tex.py from notes/math_review/\n"


def read_json(path: Path) -> Dict[str, Any]:
    if not path.exists():
        raise FileNotFoundError(f"Missing required input: {path}")
    return json.loads(path.read_text())


def fmt(x: Any, sig: int = 3) -> str:
    """Format a number for TeX math mode with `sig` significant digits."""
    val = float(x)
    if val == 0:
        return "0"
    exp = math.floor(math.log10(abs(val)))
    if -2 <= exp <= 2:
        decimals = max(sig - 1 - exp, 0)
        return f"{val:.{decimals}f}"
    mant = val / 10**exp
    if round(abs(mant), sig - 1) >= 10:
        mant /= 10
        exp += 1
    return f"{mant:.{sig - 1}f}\\times 10^{{{exp}}}"


def fmt_set(values: Sequence[Any]) -> str:
    parts = []
    for v in values:
        parts.append(str(int(v)) if float(v).is_integer() else f"{float(v):g}")
    return r"\{" + ",".join(parts) + r"\}"


def macro(name: str, value: str) -> str:
    return f"\\newcommand{{\\{name}}}{{\\ensuremath{{{value}}}}}"


def write(name: str, content: str) -> None:
    (OUT_DIR / name).write_text(HEADER + content.rstrip() + "\n", encoding="utf-8")


def table(caption: str, label: str, columns: str, head: List[str], rows: List[List[str]],
          pre_head: str = "") -> str:
    lines = ["\\begin{table}[htbp]", "\\centering", f"\\caption{{{caption}}}",
             f"\\label{{{label}}}", "\\small", f"\\begin{{tabular}}{{{columns}}}", "\\toprule"]
    if pre_head:
        lines.append(pre_head)
    lines.append(" & ".join(head) + r" \\")
    lines.append("\\midrule")
    lines.extend(" & ".join(r) + r" \\" for r in rows)
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    return "\n".join(lines)


def main() -> int:
    d = {key: read_json(path) for key, path in INPUTS.items()}
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    m: List[str] = []

    # Stencils.
    base, legacy = d["stencil_baseline"], d["stencil_legacy"]
    matched, hunt = d["stencil_matched"], d["stencil_hunt"]
    m.append(macro("StencilBaselineTotal", str(base["generated_total"])))
    m.append(macro("StencilBaselineSurvivors", str(base["survivors_total"])))
    m.append(macro("StencilBaselineOrderZero", str(base["survivors_by_best_fit_k"]["0"])))
    m.append(macro("StencilLegacyTested", str(legacy["counts"]["tested_total"])))
    m.append(macro("StencilLegacySurvivors", str(legacy["counts"]["survivors_total"])))
    ablation = legacy["ablation_same_candidates"]
    m.append(macro("StencilLegacyTestedOrderOne", str(ablation["tested_by_best_fit_k"].get("1", 0))))
    m.append(macro("StencilLegacyStabilityOnly", str(sum(ablation["stability_only_by_best_fit_k"].values()))))
    mp = matched["params"]
    m.append(macro("StencilMatchedTotal", str(matched["generated_total"])))
    m.append(macro("StencilMatchedPerOrder", str(mp["num_per_order"])))
    m.append(macro("StencilMatchedM", str(mp["m"])))
    m.append(macro("StencilMatchedNZero", str(mp["N0"])))
    m.append(macro("StencilMatchedDTwoMax", fmt(mp["D2_max"], 2)))
    m.append(macro("StencilMatchedRatioMax", fmt(mp["ratio_max"], 2)))
    before = matched["stability_only_by_best_fit_k"]
    after = matched["stability_and_leibniz_by_best_fit_k"]
    for k, word in enumerate(["Zero", "One", "Two"]):
        m.append(macro(f"StencilMatchedStable{word}", str(before[str(k)])))
        m.append(macro(f"StencilMatchedLeibniz{word}", str(after[str(k)])))
    m.append(macro("StencilMatchedStableTotal", str(sum(before.values()))))
    m.append(macro("StencilMatchedLeibnizTotal", str(sum(after.values()))))
    counts = hunt["counts"]
    m.append(macro("StencilHuntTested", str(counts["tested_total"])))
    m.append(macro("StencilHuntPerMode", str(counts["tested_by_mode"]["moment1"])))
    m.append(macro("StencilHuntPassed", str(counts["passed_leibniz_total"])))
    m.append(macro("StencilHuntFalsePositives", str(counts["false_positive_total"])))
    m.append(macro("StencilHuntMinF", fmt(hunt["params"]["thresholds"]["minF"], 2)))

    records = matched["records"]
    agree = sum(r["scale_order"] == r["best_fit_k"] for r in records)
    m.append(macro("StencilMatchedLabelAgreement", str(agree)))
    by_fit = {k: sum(r["best_fit_k"] == k for r in records) for k in range(3)}
    rows = [[f"$k={k}$", str(by_fit[k]), str(before[str(k)]), str(after[str(k)])]
            for k in range(3)]
    rows.append(["Total", str(matched["generated_total"]), str(sum(before.values())),
                 str(sum(after.values()))])
    write("stencil_matched_table.tex", table(
        "Matched stencil population, counted by best-fit template order (which coincides with "
        "the declared scaling order for every candidate). The same candidates are evaluated "
        "under both gates; the fit label is recorded after acceptance and never used as a gate.",
        "tab:stencil-matched", "lrrr",
        ["Fit order", "Candidates", "Stability only", "Stability + Leibniz"], rows))

    # Coordinate-change route mismatch.
    hol = d["holonomy"]
    m.append(macro("HolonomyEps", fmt(hol["params"]["eps"], 2)))
    m.append(macro("HolonomyNList", fmt_set(hol["params"]["N_list"])))
    m.append(macro("HolonomyExponent", fmt(hol["fit"]["p"], 3)))
    m.append(macro("HolonomyFitRtwo", fmt(hol["fit"]["r2"], 3)))
    null_max = max(r["rm"] for r in hol["null_results"])
    m.append(macro("HolonomyNullRMMax", fmt(null_max)))
    hr = hol["results"]
    m.append(macro("HolonomyRMFinest", fmt(hr[-1]["rm"])))
    rows = [[f"{r['N']}", f"${fmt(r['h'])}$", f"${fmt(r['rm'])}$",
             f"${fmt(r['route_A_rms_error'])}$", f"${fmt(r['route_B_rms_error'])}$"] for r in hr]
    write("holonomy_table.tex", table(
        "Coordinate-change diagnostic: relative route mismatch and the RMS error of each route "
        "against the exact derivative $g'(\\varphi(x))$.",
        "tab:holonomy", "rrrrr",
        ["$N$", "$h$", "$\\mathrm{RM}(h)$", "Route A error", "Route B error"], rows))

    # Integration.
    integ = d["integration"]["results"]
    fits = integ["fits"]
    irows = integ["rows"]
    m.append(macro("IntegrationNList", fmt_set(d["integration"]["params"]["N_list"])))
    m.append(macro("IntegrationRMAtSmallestH", fmt(irows[-1]["rm_max"])))
    m.append(macro("IntegrationRMExponent", fmt(fits["rm_max"]["slope"], 4)))
    m.append(macro("IntegrationFTExponent", fmt(fits["ft_trap_max"]["slope"], 4)))
    m.append(macro("IntegrationLeftTruthFinest", fmt(irows[-1]["integral_left_weighted_l2_error_max"])))
    m.append(macro("IntegrationTrapTruthFinest", fmt(irows[-1]["integral_trap_weighted_l2_error_max"])))
    left_max = max(r["ft_left_max"] for r in irows)
    add_max = max(max(r["add_left_max"], r["add_trap_max"]) for r in irows)
    m.append(macro("IntegrationFTLeftMax", fmt(left_max, 2)))
    m.append(macro("IntegrationAddMax", fmt(add_max, 2)))
    rows = [[f"{r['N']}", f"${fmt(r['rm_max'])}$", f"${fmt(r['ft_trap_max'])}$",
             f"${fmt(r['ft_trap_weighted_l2_max'])}$",
             f"${fmt(r['integral_left_weighted_l2_error_max'])}$",
             f"${fmt(r['integral_trap_weighted_l2_error_max'])}$"] for r in irows]
    write("integration_table.tex", table(
        "Integration diagnostics, each maximized over the test family. "
        "RM is the relative left/trapezoid route mismatch; $\\mathrm{FT}_T$ is the trapezoid "
        "fundamental-theorem defect in the raw and $\\sqrt h$-weighted $\\ell^2$ norms; the last "
        "two columns are $\\sqrt h$-weighted errors against the exact antiderivative.",
        "tab:integration", "rrrrrr",
        ["$N$", "RM", "$\\mathrm{FT}_T$ raw", "$\\mathrm{FT}_T$ weighted",
         "Left error", "Trapezoid error"], rows))

    # Prime closures.
    pr = d["prime"]
    pp = pr["params"]
    m.append(macro("PrimeDPS", str(pp["dps"])))
    m.append(macro("PrimeNList", fmt_set(pp["N_list"])))
    m.append(macro("PrimeSigmaConvList", fmt_set(pp["sigma_conv_list"])))
    m.append(macro("PrimeSigmaStripList", fmt_set(pp["sigma_strip_list"])))
    m.append(macro("PrimeTList", fmt_set(pp["t_list"])))
    conv, strip = pr["results"]["conv"], pr["results"]["strip"]
    m.append(macro("PrimeRMConvAtEightHundred", fmt(conv[-1]["rm2"])))
    m.append(macro("PrimeRMStripAtEightHundred", fmt(strip[-1]["rm2"])))
    m.append(macro("PrimeRMStripAtFifty", fmt(strip[0]["rm2"])))
    m.append(macro("PrimeErrPStripAtEightHundred", fmt(strip[-1]["errP2"])))
    m.append(macro("PrimeErrSStripAtEightHundred", fmt(strip[-1]["errS2"])))
    prec = d["verification"]["prime"]["precision"]
    m.append(macro("PrimeCheckDPS", str(max(prec["compared_dps"]))))
    rows = [[f"{c['N']}", f"${fmt(c['rm2'])}$", f"${fmt(c['errS2'])}$", f"${fmt(c['errP2'])}$",
             f"${fmt(s['rm2'])}$", f"${fmt(s['errS2'])}$", f"${fmt(s['errP2'])}$"]
            for c, s in zip(conv, strip)]
    write("prime_rm_table.tex", table(
        "Prime closure diagnostics. Left: convergence region with one-sided completion. "
        "Right: critical strip with symmetrized completion.",
        "tab:prime-rm", "r rrr rrr",
        ["$N$", "$\\mathrm{RM}_2$", "$\\mathrm{Err}_S$", "$\\mathrm{Err}_P$",
         "$\\mathrm{RM}_2$", "$\\mathrm{Err}_S$", "$\\mathrm{Err}_P$"], rows,
        pre_head="& \\multicolumn{3}{c}{$\\Re(s)\\in\\PrimeSigmaConvList$} & "
                 "\\multicolumn{3}{c}{$\\Re(s)\\in\\PrimeSigmaStripList$} \\\\\n"
                 "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}"))

    # Positivity toy.
    pa = d["passivity"]
    pap = pa["params"]
    m.append(macro("PassivityN", str(pap["n"])))
    m.append(macro("PassivityBeta", fmt(pap["beta"], 1)))
    m.append(macro("PassivityJScale", fmt(pap["J_scale"], 1)))
    res = {float(r["lambda"]): r for r in pa["results"]}
    m.append(macro("PassivityMeanDevLamOne", fmt(res[1.0]["mean_dev"])))
    m.append(macro("PassivityMaxDevLamOne", fmt(res[1.0]["max_dev"])))
    m.append(macro("PassivityMeanDevLamZero", fmt(res[0.0]["mean_dev"], 2)))
    m.append(macro("PassivityMaxDevLamZero", fmt(res[0.0]["max_dev"], 2)))
    m.append(macro("PassivityComponentsLamZero",
                   ",".join(str(x) for x in res[0.0]["component_degrees"])))
    ver = {float(v["lambda"]): v for v in d["verification"]["passivity"]}
    m.append(macro("PassivityCheckDPS", str(ver[0.0]["dps"])))
    m.append(macro("PassivityMatchLamOne", fmt(ver[1.0]["root_match_max_distance"], 2)))
    m.append(macro("PassivityMatchLamZero", fmt(ver[0.0]["root_match_max_distance"], 2)))
    rows = [[f"${fmt(r['lambda'], 1)}$", ",".join(str(x) for x in r["component_degrees"]),
             f"${fmt(r['mean_dev'])}$", f"${fmt(r['max_dev'])}$"] for r in pa["results"]]
    write("passivity_table.tex", table(
        "Positivity toy: radial deviation of the zeros from the unit circle. The second column "
        "lists the degrees of the component factors of $Z_\\lambda$; at $\\lambda=0$ the "
        "deviations are at floating-point roundoff.",
        "tab:passivity", "rlrr",
        ["$\\lambda$", "Component degrees", "mean\\_dev", "max\\_dev"], rows))

    # Verification summary.
    v = d["verification"]
    m.append(macro("LeanExportCount", str(len(v["lean"]["audited_exports"]))))
    m.append(macro("PythonTestsPassed", str(v["tests_passed"])))

    write("macros.tex", "\n".join(m))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
